package layout

import "math"

// Геометрия: числа сняты с настоящих файлов, а не выбраны.
//
// Эталон — `examples/тест.rsf`: модель, собранную в Ramus и ни разу не
// правленную (все четыре подработы одного размера, значит их не двигали).
// Подтверждение — `examples/ФормированиеТП.rsf`, где две работы первого уровня
// стоят ровно в тех же точках.
const (
	// Диагональ, по которой Ramus расставляет блоки диаграммы.
	startX, startY = 80.0, 80.0
	endX, endY     = 660.0, 322.0

	// Размер блока. Отношение высоты к ширине — ровно 0.7.
	blockWidth  = 72.0
	blockHeight = 50.4
	aspect      = blockHeight / blockWidth

	// Лист. Измерено по крайним точкам стрелок «Изготовления юбки»: граничные
	// сегменты начинаются ровно на краю.
	sheetLeft, sheetRight = 7.0, 793.0
	sheetTop, sheetBottom = 7.0, 437.0
)

// Ниже — не измерение, а решение, и обозначено так намеренно.
const (
	// minWidth — ниже блок нечитаем.
	minWidth = 24.0
	// gap — просвет между соседями при сжатии, чтобы блоки не слипались.
	gap = 6.0

	// channelStep — на сколько отходит стрелка, которой не досталось
	// канонической линии.
	//
	// Меры нет и быть не может: двух стрелок в одном промежутке не нарисовано
	// ни в одной модели Ramus из набора, мерить не на чем. Взят gap — просвет,
	// который в пакете уже есть и уже помечен как решение; заводить вторую
	// константу того же порядка ради того же смысла незачем.
	channelStep = gap

	// maxChannels — сколько линий перебирать, прежде чем сдаться и оставить
	// каноническую. Двадцать пять шагов по 6.0 — 150 единиц в каждую сторону,
	// пятая часть листа: дальше отодвинутая стрелка перестаёт читаться как та
	// же самая, и наложение из двух зол меньшее.
	maxChannels = 25

	// portGap — наименьший промежуток между соседними стрелками одной стороны
	// блока. Уже него стрелки не различить глазом и не ухватить мышью: под
	// курсором оказывается соседняя.
	//
	// Решение, а не мера. Авто-раскладка Ramus при двух стрелках на стороне
	// ставит их в 16.8 друг от друга, в правленных руками моделях теснее 15 —
	// два промежутка из двадцати семи, а ровно 15 Ramus не ставит нигде
	// (specs/012-arrow-port-spacing). Начинали с 20 — но тогда рос бы почти
	// каждый блок с двумя входами, чего Ramus не делает. Число пробное и
	// правится здесь одной строкой.
	portGap = 15.0
)

// grow растит блок под его стрелки.
//
// Стрелки делят сторону на n+1 равных частей (assignSlots), значит промежуток
// между соседями — длина стороны, делённая на n+1. Чтобы он был не меньше
// portGap, сторона должна быть не короче (n+1)·portGap. Входы и выходы лежат
// на вертикальных сторонах и растят высоту, управление и механизмы — ширину;
// ось, на которой не тесно, остаётся прежней, пропорция не сохраняется
// намеренно: блок с семью входами, раздутый до 171 в ширину, съел бы
// промежутки, в которых идут маршруты.
func grow(width, height float64, n need) (float64, float64) {
	return math.Max(width, float64(max(n.control, n.mechanism)+1)*portGap),
		math.Max(height, float64(max(n.in, n.out)+1)*portGap)
}

// box — прямоугольник блока. Имя нужно маршрутам: они ищут прямоугольник по
// концу стрелки, а тот назван работой.
type box struct {
	x, y, width, height float64
	owner               string
}

// place расставляет блоки одной диаграммы по диагонали.
//
// На входе — спрос блоков в порядке лестницы: сколько стрелок у каждой
// стороны. Возвращает столько прямоугольников, сколько запрошено, в том же
// порядке: первый — в начале диагонали, последний — в конце.
func place(needs []need) []box {
	n := len(needs)
	if n == 0 {
		return nil
	}
	if n == 1 {
		// Делить диагональ не на что. Куда Ramus кладёт единственный блок,
		// наблюдать не на чем: у корневых работ трёх моделей центры разные, и
		// в двух из трёх блок растянут руками. Центр листа — единственный
		// выбор, который не выдаёт догадку за измерение. Выросший блок растёт
		// вокруг того же центра.
		width, height := grow(blockWidth, blockHeight, needs[0])
		return []box{{
			x:      (sheetLeft+sheetRight)/2 - width/2,
			y:      (sheetTop+sheetBottom)/2 - height/2,
			width:  width,
			height: height,
		}}
	}

	stepX := (endX - startX) / float64(n-1)
	stepY := (endY - startY) / float64(n-1)
	baseWidth, baseHeight := size(stepX)

	out := make([]box, n)
	var sumWidth, sumHeight float64
	for i := range out {
		out[i].width, out[i].height = grow(baseWidth, baseHeight, needs[i])
		sumWidth += out[i].width
		sumHeight += out[i].height
	}

	// Лестница — равные промежутки между соседями вдоль прежнего размаха.
	//
	// Размах — от левого верхнего угла первого блока до правого нижнего угла
	// последнего, ровно как у Ramus. Промежуток — что остаётся от размаха
	// после блоков, поровну между соседями. При равных размерах это та же
	// формула, что снята с `тест.rsf`: x_i = 80 + i·stepX, до знака. При
	// разных — выросшие блоки съедают промежутки, а не выталкивают соседей,
	// и правый нижний угол лестницы остаётся на месте, внутри листа.
	//
	// По вертикали промежуток бывает отрицательным: соседи перекрываются по
	// высоте. Это не авария — при шести работах так делает и сам Ramus (шаг
	// 48.4 при высоте 50.4), — блоки разводит горизонталь.
	//
	// Считается поправкой к прежней формуле, а не суммой с нуля: шаг от блока
	// к следующему — stepX плюс прирост этого блока минус его доля общего
	// прироста. Без роста поправка ровно ноль, и координата выходит теми же
	// операциями, что и прежде, — побайтово тот же файл. Сумма ширин с
	// промежутками дала бы то же число с точностью до последнего знака, а
	// последний знак в файле виден.
	excessX := (sumWidth - float64(n)*baseWidth) / float64(n-1)
	excessY := (sumHeight - float64(n)*baseHeight) / float64(n-1)

	// Две страховки. Горизонтальный промежуток — то, что держит блоки
	// порознь и где идут маршруты, поэтому рост не вправе сузить его ниже
	// просвета. Подъём от блока к следующему — то, что делает лестницу
	// лестницей: одна высокая работа рядом с низкой съела бы весь
	// вертикальный размах, и следующий блок встал бы выше предыдущего.
	//
	// Пол у обеих — не больше того, что лестница даёт без роста: с двадцати
	// четырёх работ промежуток и так уже 1.2 (size, minWidth), и страховка не
	// должна вытягивать то, что не росло. Сработавшая страховка вытягивает
	// лестницу дальше прежнего угла; не вместилась в лист — названная
	// граница, как с двадцати шести работ в size(). На наборе не срабатывает
	// ни одна.
	floorX := math.Min(gap, stepX-baseWidth)
	floorY := math.Min(gap, stepY)

	// Промежуток между соседями по горизонтали одинаков для всех пар; подъём
	// у каждой пары свой — он зависит от высоты верхнего блока.
	gapX := stepX - baseWidth - excessX
	var shiftX, shiftY float64
	for i := range out {
		out[i].x = startX + float64(i)*stepX + shiftX
		out[i].y = startY + float64(i)*stepY + shiftY

		shiftX += (out[i].width - baseWidth) - excessX + math.Max(0, floorX-gapX)
		rise := stepY + (out[i].height - baseHeight) - excessY
		shiftY += (out[i].height - baseHeight) - excessY + math.Max(0, floorY-rise)
	}
	return out
}

// size подбирает размер блока под горизонтальный шаг.
//
// Блоки пересекаются, только когда тесно и по горизонтали, и по вертикали.
// Диагональ разносит их по горизонтали, поэтому смотреть достаточно на шаг по
// X: до девяти блоков он больше ширины, и сжимать нечего. С десяти блок
// мельчает, сохраняя пропорцию.
//
// С двадцати шести блоков шаг становится меньше наименьшей ширины, и наложение
// возвращается. Это названная граница: двадцать пять блоков на одной диаграмме
// — далеко за каноном IDEF0 (3–6), и делать вид, что лист вмещает
// бесконечность, хуже, чем сказать, где он кончается.
func size(stepX float64) (width, height float64) {
	if stepX >= blockWidth {
		// Блоки и так расходятся — сжимать нечего. Зазор здесь не нужен:
		// вычитать его, пока места хватает, значило бы мельчить картинку там,
		// где Ramus её не мельчит.
		return blockWidth, blockHeight
	}

	width = stepX - gap
	if width < minWidth {
		width = minWidth
	}
	return width, width * aspect
}
