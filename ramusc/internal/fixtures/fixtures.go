// Пакет fixtures перечисляет настоящие модели Ramus, на которых проверяется
// разбор .rsf. Список лежит здесь, а не в testdata: каталог с таким именем
// инструментарий Go при сборке пропускает, и пакет оттуда не импортируется.
//
// Пакет нужен только тестам. В бинарь он не попадает: cmd/ramusc его не
// импортирует.
package fixtures

import (
	"path/filepath"
	"runtime"
)

// Model — проверочная модель.
type Model struct {
	// Path — абсолютный путь к файлу.
	Path string
	// Name — короткое имя для сообщений теста.
	Name string
	// ExpectRefusal — файл содержит то, что входным языком не выражается,
	// и декомпиляция обязана отказать. Без этого признака табличный тест
	// требовал бы от всех моделей одинакового исхода, а они по делу разные.
	ExpectRefusal bool
}

// All отдаёт перечень моделей. Добавление файла сюда подхватывается всеми
// табличными проверками без правки их кода.
func All() []Model {
	return []Model{
		{
			Path: repoPath("examples", "ИзготовлениеЮбки.rsf"),
			Name: "ИзготовлениеЮбки",
		},
		{
			// Четыре живые работы из пяти без имени: имя работы — её
			// идентификатор (Р4), пустых быть не может, и файл языком не
			// выражается.
			Path:          repoPath("ramusc", "testdata", "testModel.rsf"),
			Name:          "testModel",
			ExpectRefusal: true,
		},
		{
			// Работа с запятой в имени: она попадает в потоковые списки и
			// отображения, где запятая разделяет элементы. Модель держит
			// правило кавычек в писателе.
			//
			// Одна стрелка нарисована без имени и разветвлена на два
			// приёмника: языком она не выражается (Р18), и файл отвергается.
			Path:          repoPath("examples", "ФормированиеТП.rsf"),
			Name:          "ФормированиеТП",
			ExpectRefusal: true,
		},
		{
			// Минимальный воспроизводитель стрелки без имени, собранный в
			// самом Ramus: цепочка из четырёх подработ, у которой названы
			// только пять граничных стрелок, а три внутренние — нет.
			// Без него правило проверялось бы только на модели, где
			// безымянная стрелка ещё и ветвится.
			Path:          repoPath("examples", "тест.rsf"),
			Name:          "тест",
			ExpectRefusal: true,
		},
	}
}

// repoPath разрешает путь от корня репозитория. Считать от текущего каталога
// нельзя: go test запускает каждый пакет в его собственном каталоге, и один и
// тот же относительный путь означал бы разное в разных пакетах.
func repoPath(parts ...string) string {
	_, self, _, ok := runtime.Caller(0)
	if !ok {
		panic("fixtures: не удалось определить путь пакета")
	}
	// self — .../ramusc/internal/fixtures/fixtures.go, корень тремя уровнями выше.
	root := filepath.Join(filepath.Dir(self), "..", "..", "..")
	return filepath.Join(append([]string{root}, parts...)...)
}
